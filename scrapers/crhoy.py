# SCRAPING PRINCIPAL
# -------------------------------------------------------------
data = []
urls_vistas = set()

EXCLUIR = ['/busqueda', '/pro', '/autor', '/categoria',
           '/gusto/guias', '/gusto/recomendaciones',
           '/programa', '/membresia', '/nosotros',
           '/contacto', '/enterese', '/caricatura', '#']

with requests.Session() as session:
    session.headers.update(HEADERS)

    for section, url_seccion in SECCIONES.items():
        print(f"\nSeccion: {section.upper()} -> {url_seccion}")

        main_soup = get_soup(url_seccion, session)
        if main_soup is None:
            print(f"  No se pudo acceder.")
            continue

        links = []
        for a in main_soup.find_all('a', href=True):
            href = a['href']
            if (href.startswith('/') and
                len(href) > 10 and
                not any(x in href for x in EXCLUIR)):
                full = BASE_URL + href
                if full not in urls_vistas:
                    if a.find(['h2', 'h3']) or a.find(class_=re.compile(r'text-body')):
                        links.append(full)
                        urls_vistas.add(full)

        print(f"  {len(links)} articulos nuevos encontrados.")

        for i, link in enumerate(links, 1):
            print(f"    [{i}/{len(links)}] {link.split('/')[-2][:55]}...")
            time.sleep(DELAY)

            article_soup = get_soup(link, session)
            if article_soup:
                title, date, section_real, content = extract_article_data(article_soup)
            else:
                title, date, section_real, content = "Error", "Error", section, "Error al recuperar"

            data.append({
                'source':           'crhoy',
                'url':              link,
                'title':            title,
                'publication_date': date,
                'scraping_date':    datetime.now().strftime('%Y-%m-%d %H:%M:%S'),
                'section':          section_real,
                'full_text':        content,
                'language':         'es'
            })

