def get_soup(url, session):
    """Petición HTTP → BeautifulSoup. Retorna None si falla."""
    try:
        response = session.get(url, timeout=10)
        response.raise_for_status()
        return BeautifulSoup(response.text, 'html.parser')
    except requests.RequestException as e:
        print(f"  Error: {url} -> {e}")
        return None

def clean_text(text):
    """Elimina espacios y saltos de línea extra."""
    return re.sub(r'\s+', ' ', text).strip() if text else ""

def parse_date_crhoy(text):
    """
    Convierte "6 de Abr. 2026 | 1:35 am" → "2026-04-06"
    También maneja "2026-04-06T01:35:25" directo.
    """
    if not text:
        return "Sin fecha"
    text = text.strip()
    if re.match(r'\d{4}-\d{2}-\d{2}', text):
        return text[:10]
    m = re.search(r'(\d{1,2})\s+de\s+(\w+)\.?\s+(\d{4})', text, re.IGNORECASE)
    if m:
        dia  = m.group(1).zfill(2)
        mes  = MESES.get(m.group(2).lower()[:3], '01')
        anio = m.group(3)
        return f"{anio}-{mes}-{dia}"
    return "Sin fecha"

def extract_article_data(soup):
    """
    Extrae título, fecha, sección y contenido del artículo.
    Estructura HTML de crhoy.com (Next.js + Tailwind):
      - Meta JSON: <script id="__cr_post_meta"> {"author":...,"category":...}
      - Título:    <h1>
      - Fecha:     <span> con patrón "6 de Abr. 2026 | 1:35 am"
      - Sección:   del JSON o etiqueta naranja
      - Contenido: <div class="...wp-article..."> → <p>
    """
    # --- Sección desde JSON embebido ---
    section = "sin-seccion"
    meta_tag = soup.find('script', id='__cr_post_meta')
    if meta_tag:
        try:
            meta = json.loads(meta_tag.string)
            raw_sec = meta.get('category', '')
            if raw_sec:
                section = raw_sec.lower()
                section = section.replace('á','a').replace('é','e').replace('í','i').replace('ó','o').replace('ú','u')
                section = re.sub(r'\s+', '-', section).strip('-')
        except Exception:
            pass

    # Fallback: etiqueta naranja sobre el título
    if section == "sin-seccion":
        tag = soup.find('span', class_=re.compile(r'orange-label|bg-orange'))
        if tag:
            section = clean_text(tag.get_text()).lower()
            section = section.replace('á','a').replace('é','e').replace('í','i').replace('ó','o').replace('ú','u')
            section = re.sub(r'\s+', '-', section).strip('-')

    # --- Título ---
    title_tag = soup.find('h1')
    title = clean_text(title_tag.get_text()) if title_tag else "Sin titulo"

    # --- Fecha ---
    date = "Sin fecha"
    for span in soup.find_all('span'):
        txt = clean_text(span.get_text())
        if re.search(r'\d{1,2}\s+de\s+\w+', txt, re.IGNORECASE):
            date = parse_date_crhoy(txt)
            if date != "Sin fecha":
                break
    # Fallback desde JSON
    if date == "Sin fecha" and meta_tag:
        try:
            meta = json.loads(meta_tag.string)
            raw_date = meta.get('date', '')
            if raw_date:
                date = raw_date[:10]
        except Exception:
            pass

    # --- Contenido ---
    content = "Contenido no encontrado"
    content_div = soup.find('div', class_=re.compile(r'wp-article'))
    if not content_div:
        content_div = soup.find('article')
    if content_div:
        for tag in content_div.find_all(['script', 'style', 'iframe', 'aside', 'figure', 'noscript']):
            tag.decompose()
        parrafos = content_div.find_all('p')
        if parrafos:
            content = " ".join(clean_text(p.get_text()) for p in parrafos if p.get_text(strip=True))
        else:
            content = clean_text(content_div.get_text())

    return title, date, section, content

