# -------------------------------------------------------------
# CONFIGURACIÓN
# -------------------------------------------------------------
BASE_URL = 'https://crhoy.com'

SECCIONES = {
    'nacionales':     'https://crhoy.com/nacionales/',
    'mundo':          'https://crhoy.com/mundo/',
    'economia':       'https://crhoy.com/economia/',
    'deportes':       'https://crhoy.com/deportes/',
    'entretenimiento':'https://crhoy.com/entretenimiento/',
    'tecnologia':     'https://crhoy.com/tecnologia/',
    'gusto':          'https://crhoy.com/gusto/',
}

HEADERS = {'User-Agent': 'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/120.0.0.0 Safari/537.36'}
DELAY = 1.5

MESES = {
    'ene':'01','feb':'02','mar':'03','abr':'04',
    'may':'05','jun':'06','jul':'07','ago':'08',
    'sep':'09','oct':'10','nov':'11','dic':'12'
}

